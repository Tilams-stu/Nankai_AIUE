def set_font(run, name="宋体", size=11, bold=False):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run._element.rPr.rFonts.set(qn("w:ascii"), "Times New Roman")
    run._element.rPr.rFonts.set(qn("w:hAnsi"), "Times New Roman")
    run.font.size = Pt(size)
    run.bold = bold


def configure_document(doc):
    section = doc.sections[0]
    section.top_margin = Inches(1)
    section.bottom_margin = Inches(1)
    section.left_margin = Inches(1)
    section.right_margin = Inches(1)

    normal = doc.styles["Normal"]
    normal.font.name = "宋体"
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    normal._element.rPr.rFonts.set(qn("w:ascii"), "Times New Roman")
    normal._element.rPr.rFonts.set(qn("w:hAnsi"), "Times New Roman")
    normal.font.size = Pt(11)
    normal.paragraph_format.line_spacing = 1.25
    normal.paragraph_format.space_after = Pt(4)


def add_paragraph(doc, text, size=11, bold=False, before=0, after=4):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    run = p.add_run(text)
    set_font(run, size=size, bold=bold)
    return p


def build_report(day, data):
    out_dir = OUT_ROOT / day
    out_dir.mkdir(parents=True, exist_ok=True)

    doc = Document()
    configure_document(doc)

    add_paragraph(doc, data["title"], size=14, bold=True, after=6)
    add_paragraph(doc, data["module"], size=11, after=4)
    add_paragraph(doc, data["intro"], size=11, after=8)

    for heading, items in data["sections"]:
        add_paragraph(doc, heading, size=12, bold=True, before=8, after=4)
        for item in items:
            add_paragraph(doc, item, size=11, after=4)

    path = out_dir / data["filename"]
    doc.save(path)
    return path


def main():
    for day, data in REPORTS.items():
        print(build_report(day, data))


if __name__ == "__main__":
    main()
